import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const cwd = fileURLToPath(new URL('../', import.meta.url));
const git = args => execFileSync('git', args, {cwd, encoding:'utf8', stdio:['ignore', 'pipe', 'ignore']}).trim();
let commit = 'unversioned';
try {
  commit = git(['rev-parse', '--short=12', 'HEAD']);
  if (git(['status', '--porcelain'])) commit += '-dirty';
} catch {}
const builtAt = new Date().toISOString().slice(0, 19).replace('T', ' ') + ' GMT';
const build = { commit, builtAt, label: 'AtTune [' + commit + '] ' + builtAt, cacheVersion: commit + '-' + Date.now() };
await writeFile(new URL('../version.js', import.meta.url), '// Generated by npm run build; do not edit.\nglobalThis.ATTUNE_BUILD = Object.freeze(' + JSON.stringify(build) + ');\n');
console.log(build.label);
